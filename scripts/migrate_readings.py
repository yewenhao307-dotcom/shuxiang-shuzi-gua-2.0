def invariant_hash(readings: list[dict]) -> str:
    rows: list[str] = []
    for reading in readings:
        rows.append(f"{reading['id']}|{reading['name']}|{reading['upper_trigram']}|{reading['lower_trigram']}|{reading['source_note']}")
        for number in range(1, 7):
            line = reading["lines"][str(number)]
            rows.append(f"{number}|{line['title']}|{line['classic']}|{line['source']}")
    return hashlib.sha256("\n".join(rows).encode("utf-8")).hexdigest()


def profile_for(reading: dict) -> dict:
    values = PROFILES[reading["id"]]
    profile = dict(zip(PROFILE_KEYS, values))
    return {
        "core": profile["core"],
        "strengths": [profile["strength"], reading["reflection"].split("；", 1)[0].rstrip("。")],
        "tensions": [profile["tension"]],
        "risks": [profile["risk"]],
        "actions": [profile["action"]],
        "avoid": [profile["avoid"]],
        "questions": [profile["question"]],
    }


def signal_for(classic: str) -> tuple[str, str]:
    for markers, label, explanation in SIGNALS:
        if any(marker in classic for marker in markers):
            return label, explanation
    return "观察", "爻辞没有把结果写成单一结论，更适合把其中的处境和动作当作观察线索"


