def migrate(readings: list[dict]) -> list[dict]:
    if invariant_hash(readings) != FACT_SHA256:
        raise ValueError("Canonical fact hash does not match the expected baseline; migration stopped.")
    if set(PROFILES) != set(range(1, 65)):
        raise ValueError("Profiles must cover all 64 hexagrams.")
    for reading in readings:
        profile = profile_for(reading)
        reading["modern"] = profile
        for number in range(1, 7):
            line = reading["lines"][str(number)]
            modern = modern_line(reading, number, line, profile)
            line["interpretation"] = modern.pop("interpretation")
            line["modern"] = modern
    if invariant_hash(readings) != FACT_SHA256:
        raise ValueError("Canonical facts changed during migration.")
    return readings


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("input", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    readings = json.loads(args.input.read_text(encoding="utf-8"))
    migrated = migrate(readings)
    args.output.write_text(json.dumps(migrated, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"MIGRATED_HEXAGRAMS={len(migrated)}")
    print(f"MIGRATED_LINES={sum(len(r['lines']) for r in migrated)}")
    print(f"FACT_SHA256={invariant_hash(migrated)}")


if __name__ == "__main__":
    main()
